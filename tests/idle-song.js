const assert=require('node:assert/strict');
const {IdleSongGate}=require('../idle-song');
const {normalizePreferences}=require('../preferences');
const gate=new IdleSongGate(0);
const sample=(now,idleSeconds,extra={})=>gate.sample({now,idleSeconds,enabled:true,available:true,blocked:false,...extra});
assert.equal(sample(299000,299),'wait');
assert.equal(sample(300000,300),'play');
assert.equal(sample(600000,600),'wait','one song per idle period, including ended/error');
assert.equal(sample(600500,0),'stop','returning user stops song');
assert.equal(sample(900000,299),'wait');
assert.equal(sample(901000,300),'play');
assert.equal(sample(902000,301,{blocked:true}),'stop','lock/hide blocks');
assert.equal(sample(903000,900),'wait','resume cannot immediately retrigger');
assert.equal(sample(1203000,1200),'play');
assert.equal(sample(1204000,1201,{enabled:false}),'stop');
assert.equal(sample(1205000,1202),'wait','enabling begins fresh five minutes');
assert.equal(sample(1506000,1503,{available:false}),'stop');
assert.equal(sample(1507000,NaN),'stop');
gate.reset(2000000);
assert.equal(sample(2000000,2000),'wait','startup after long inactivity does not surprise');
assert.equal(sample(2300000,2300),'play');
assert.equal(sample(2301000,2),'stop','idle falling detects input even if polling skipped second zero');
const prefs=normalizePreferences({idleSongVolume:99,idleSongFile:'../../bad.mp3',idleSongEnabled:'yes',idleSongMode:'remote'});
assert.equal(prefs.idleSongVolume,.5);assert.equal(prefs.idleSongFile,'');assert.equal(prefs.idleSongEnabled,false);assert.equal(prefs.idleSongMode,'ai');
assert.equal(normalizePreferences().idleSongVolume,.18);
console.log('Idle song gate passed: 5-minute threshold, once per idle, return, lock/hide/resume, enable, missing media, invalid idle, startup and preference validation.');
