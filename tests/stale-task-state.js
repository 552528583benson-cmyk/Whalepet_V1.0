const assert=require('node:assert/strict');
const {TaskStates,COMPLETION_MS}=require('../codex-state-follower');
let now=Date.now();
const r=new TaskStates({now:()=>now});
const emit=(id,type)=>r.consume(id,{timestamp:new Date(++now).toISOString(),type:'event_msg',payload:{type}});
emit('long','task_started');
now+=15*60_000+1;
assert.equal(r.current().message,'状态待确认');
assert.equal(r.conversations()[0].uncertain,true);
assert.equal(r.hasUnresolved(),true);
now+=48*60*60_000;
assert.equal(r.current().uncertain,true,'unresolved work does not silently age out');
emit('fresh','task_started');
assert.equal(r.current().session,'fresh','fresh work outranks uncertain ordinary work');
emit('urgent','request_user_input');
assert.equal(r.current().session,'urgent');
assert.deepEqual(r.overflow(),{count:1,uncertain:1});
emit('fourth','task_started');
assert.deepEqual(r.overflow(),{count:2,uncertain:1});
emit('long','agent_reasoning');
assert.equal(r.snapshot().find(x=>x.session==='long').uncertain,false,'new evidence clears uncertainty');
emit('long','task_complete');
assert.equal(r.current().session,'urgent','attention outranks completion');
now+=COMPLETION_MS+1;
assert.equal(r.conversations().some(x=>x.state==='ready'),false);
for(const id of ['fresh','urgent','fourth'])emit(id,'turn_aborted');
assert.equal(r.hasUnresolved(),false);
assert.equal(r.conversations().length,0);
assert.deepEqual(r.overflow(),{count:0,uncertain:0});
emit('urgent','request_user_input');now+=25*60*60_000;
assert.equal(r.current().state,'needs_input');
assert.equal(r.current().uncertain,true,'old unanswered questions stay urgent but indicate uncertainty');
console.log('PASS: 15-minute and 48-hour silence, recovery, overflow counts, urgent priority, completion and cancellation.');
