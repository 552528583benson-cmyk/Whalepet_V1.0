const assert=require('node:assert/strict');
const {TaskStates}=require('../codex-state-follower');
let now=Date.now();const r=new TaskStates({now:()=>now});
const emit=(id,type,payload)=>r.consume(id,{timestamp:new Date(++now).toISOString(),type,payload});
const ask=(id,call,count=1)=>emit(id,'response_item',{type:'function_call',name:'request_user_input_async',call_id:call,arguments:JSON.stringify({questions:Array.from({length:count},()=>({title:'fixture'}))})});
const reply=(call,index=0)=>`<send_user_message_question_reply>\n${JSON.stringify([{questionItemId:JSON.stringify(['request_user_input_async',call,index]),answer:'fixture'}])}\n</send_user_message_question_reply>`;
const itemReply=(call,index)=>emit('a','event_msg',{type:'item_completed',item:{type:'UserMessage',content:[{type:'text',text:reply(call,index)}]}});
ask('a','q1',2);ask('a','q2');ask('b','other');
emit('a','response_item',{type:'function_call_output',call_id:'q1',output:'{"accepted":true}'});
assert.equal(r.tasks.get('a').pending.size,2,'acknowledgement is not an answer');
itemReply('q1',0);assert.equal(r.tasks.get('a').pending.size,2,'partial reply retains remaining question');
itemReply('q1',0);assert.equal(r.tasks.get('a').pending.size,2,'duplicate reply is idempotent');
itemReply('unknown',0);assert.equal(r.tasks.get('a').pending.size,2);
itemReply('q1',1);assert.equal(r.tasks.get('a').pending.size,1);
emit('a','response_item',{type:'message',role:'assistant',content:[{type:'output_text',text:reply('q2')}]});
assert.equal(r.tasks.get('a').pending.size,1,'assistant text is not a user reply');
emit('a','response_item',{type:'message',role:'user',content:[{type:'input_text',text:reply('q2')}]});
assert.equal(r.tasks.get('a').state,'thinking');assert.equal(r.current().state,'needs_input','other session still needs an answer');
ask('a','new-question');itemReply('q2');
assert.equal(r.tasks.get('a').state,'needs_input','delayed duplicate cannot dismiss a newer question');
emit('a','event_msg',{type:'item_completed',item:{type:'UserMessage',content:[{type:'text',text:'ordinary next message'}]}});
assert.equal(r.tasks.get('a').state,'thinking','event-only user message resumes work');
emit('b','event_msg',{type:'user_message',message:'continue'});
assert.notEqual(r.current().state,'needs_input');
console.log('PASS: app UserMessage and response_item replies, matched questions, partial/duplicate replies, unrelated tasks and acknowledgement safety.');
