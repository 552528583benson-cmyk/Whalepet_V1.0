const assert=require('node:assert/strict');
const {TaskStates,COMPLETION_MS}=require('../codex-state-follower');
let now=Date.now();const r=new TaskStates({now:()=>now});
const emit=(id,type,payload)=>r.consume(id,{timestamp:new Date(++now).toISOString(),type,payload});
const start=id=>emit(id,'event_msg',{type:'task_started'});
const finish=id=>emit(id,'event_msg',{type:'task_complete'});
emit('old','event_msg',{type:'task_complete'});
assert.deepEqual(r.conversations(),[],'no historical/idle bubble on startup');
start('a');start('b');assert.equal(r.conversations().length,2);
const slots=r.conversations().map(t=>t.id);
finish('b');assert.equal(r.current().state,'ready','even secondary task completion gets a celebration');
assert.deepEqual(r.conversations().map(t=>t.id),slots,'bubble slots stay bound to their task');
assert.equal(r.conversations().find(t=>t.id===r.current().id).state,'ready');
now+=COMPLETION_MS-100;finish('b'); // duplicate terminal event must not extend hold
now+=101;
assert.equal(r.current().session,'a');assert.equal(r.conversations().length,1);
assert.equal(r.conversations()[0].state,'thinking');
finish('a');assert.equal(r.current().state,'ready');now+=COMPLETION_MS+1;
assert.equal(r.current().state,'idle');assert.deepEqual(r.conversations(),[]);
start('a');start('b');finish('a');
emit('b','event_msg',{type:'turn_failed'});assert.equal(r.current().state,'blocked','error beats celebration');
assert.ok(r.conversations().some(t=>t.state==='ready'),'completed task still turns green beside urgent one');
now+=COMPLETION_MS+1;assert.deepEqual(r.conversations().map(t=>t.state),['blocked']);
start('a');emit('b','event_msg',{type:'user_message'});
emit('b','response_item',{type:'function_call',name:'request_user_input_async',call_id:'q'});
finish('a');assert.equal(r.current().state,'needs_input');
now+=COMPLETION_MS+1;emit('b','event_msg',{type:'user_message'});
assert.equal(r.current().state,'thinking','no stale celebration after answering');
finish('b');start('b');assert.equal(r.current().state,'thinking','new turn cancels green');
emit('b','event_msg',{type:'turn_aborted'});assert.deepEqual(r.conversations(),[],'cancel is not success');
console.log('PASS: active-only bubbles, stable task slots, 3s green + celebration, no duplicate extension, resume other work, no idle bubbles, urgent preemption, restart/cancel.');
