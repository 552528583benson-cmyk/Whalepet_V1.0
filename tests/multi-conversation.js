const assert=require('node:assert/strict');
const {TaskStates}=require('../codex-state-follower');
let now=Date.now();const r=new TaskStates({now:()=>now,staleMs:60000,attentionMs:3600000});
const emit=(id,type,payload)=>r.consume(id,{timestamp:new Date(++now).toISOString(),type,payload});
emit('ask','response_item',{type:'function_call',name:'request_user_input_async',call_id:'q1'});
emit('ask','response_item',{type:'function_call_output',call_id:'q1'});
emit('work','event_msg',{type:'task_started'});
emit('work','response_item',{type:'function_call',name:'imagegen'});
assert.equal(r.current().session,'ask');
assert.deepEqual(r.conversations().map(x=>x.state),['needs_input','generating']);
emit('ask','response_item',{type:'reasoning'});
emit('ask','response_item',{type:'function_call',name:'apply_patch'});
emit('ask','response_item',{type:'message',role:'assistant',phase:'final'});
assert.equal(r.current().state,'needs_input','async question is independent of background/final messages');
emit('error','event_msg',{type:'turn_failed'});
assert.deepEqual(r.conversations().map(x=>x.state),['needs_input','blocked']);
now+=120000;
assert.equal(r.current().state,'needs_input','attention survives ordinary work expiry');
emit('ask','event_msg',{type:'user_message'});
assert.equal(r.current().state,'blocked','after answer next urgent conversation wins');
emit('error','event_msg',{type:'turn_started'});
assert.equal(r.current().state,'thinking');
const selected=r.current().session;
emit(selected==='ask'?'error':'ask','response_item',{type:'reasoning'});
assert.equal(r.current().session,selected,'equal priorities do not flicker');
emit('sync','response_item',{type:'function_call',name:'request_user_input',call_id:'q2'});
emit('sync','response_item',{type:'function_call_output',call_id:'unrelated'});
assert.equal(r.current().state,'needs_input');
emit('sync','response_item',{type:'function_call_output',call_id:'q2'});
assert.notEqual(r.current().state,'needs_input','matched synchronous output clears request');
emit('permission','event_msg',{type:'permission_request',request_id:'p1'});
emit('permission','event_msg',{type:'server_request_resolved',request_id:'p1'});
assert.notEqual(r.current().state,'needs_input');
emit('abort','response_item',{type:'function_call',name:'request_user_input_async',call_id:'q3'});
emit('abort','event_msg',{type:'turn_aborted'});
assert.notEqual(r.current().state,'needs_input');
assert.ok(r.conversations().every(x=>/^[a-f0-9]{8}$/.test(x.id)&&!('session' in x)),'UI never gets transcript paths/content');
now+=3600001;assert.equal(r.current().uncertain,true);
assert.equal(r.hasUnresolved(),true,'silence cannot confirm completion');
console.log('Multi-conversation priority passed: urgent priority, sticky async, matched answers, uncertainty, cancellation, stable ties, private identifiers.');
